#!/usr/bin/env python3
"""Embeds src/net/ca_roots.pem into src/net/ca_roots.c as a C string.

The PEM bundle holds the roots behind the Revival servers (Cloudflare with
Google Trust Services certificates) plus fallbacks; it was exported from the
macOS system trust store:
  security find-certificate -c "GTS Root R4" -p \\
      /System/Library/Keychains/SystemRootCertificates.keychain

Usage: scripts/gen_ca_roots.py
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(ROOT, "src", "net", "ca_roots.pem")
dst = os.path.join(ROOT, "src", "net", "ca_roots.c")

lines = [l.rstrip("\n") for l in open(src) if l.strip()]
out = ["// Generated by scripts/gen_ca_roots.py from ca_roots.pem - do not edit.", ""]
out.append("const char ca_roots_pem[] =")
for l in lines:
    if l.startswith("#"):
        out.append("    // " + l[1:].strip())
    else:
        out.append('    "%s\\n"' % l)
out.append("    ;")
out.append("")
open(dst, "w").write("\n".join(out))
print(dst, sum(1 for l in lines if "BEGIN CERTIFICATE" in l), "certificates")
