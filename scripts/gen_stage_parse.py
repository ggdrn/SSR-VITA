#!/usr/bin/env python3
"""Build guarded in-place layer batching IL from supported original bodies.
Usage: gen_stage_parse.py ReadObjects.il ReadLayer.il output.h
The test metadata harness can export the original bodies from the APK DLL.
"""
from pathlib import Path
import struct,sys
b=bytearray();labels={};fix=[]
def emit(*v):b.extend(v)
def mark(n):labels[n]=len(b)
def tok(op,t):emit(op);b.extend(struct.pack('<I',t))
def field(t):emit(2);tok(0x7b,t)
def setfield(t):tok(0x7d,t)
def call(t,virt=True):tok(0x6f if virt else 0x28,t)
def br(op,name,short=True):
 emit(op);at=len(b);b.extend(bytes(1 if short else 4));fix.append((at,len(b),name,short))
def switch(names):
 emit(6,0x45);b.extend(struct.pack('<I',len(names)));base=len(b)+len(names)*4
 for name in names:
  at=len(b);b.extend(bytes(4));fix.append((at,base,name,False))
# Same state entry and finalization as original; local 0 doubles as batch budget.
field(0x040043d8);emit(0x0a,2,0x15);setfield(0x040043d8)
switch(['layer','next_layer','batch']);emit(0x16,0x2a)
mark('layer');field(0x040043d2);emit(0x25);tok(0x72,0x7000a162);call(0x0a00127d);br(0x39,'no_attribute',False)
emit(0x25);call(0x0a00126e);call(0x0a00068e,False);emit(0x0a,2,6);setfield(0x040043d3)
emit(0x25);call(0x0a001270);emit(0x26)
tok(0x72,0x70035230);call(0x0a001271);br(0x2c,'yield_layer')
emit(2);field(0x040043d4);field(0x040043d3);tok(0x73,0x06000773);setfield(0x040043d5)
mark('batch');emit(0x1f,16,0x0a) # 16 objects per MoveNext
mark('object');field(0x040043de);field(0x040043d6);field(0x040043d2);field(0x040043d5);call(0x06003c18,False)
field(0x040043d2);tok(0x72,0x70035230);call(0x0a001275);br(0x2c,'publish')
emit(6,0x17,0x59,0x25,0x0a);br(0x2d,'object')
emit(0x18);br(0x2b,'yield')
mark('publish');field(0x040043d7);field(0x040043d4);field(0x040043d3);field(0x040043d5);call(0x06003e70)
br(0x2b,'yield_layer')
mark('no_attribute');emit(0x26)
mark('yield_layer');emit(0x17)
# Current is always null: the supported constructor initializes the field to
# null and the original coroutine yields only null. Reuse that invariant to
# fit the extra state/batch budget without growing the body or local signature.
mark('yield');emit(0x0a,2,6);setfield(0x040043d8);emit(0x17,0x2a)
mark('next_layer');field(0x040043d2);tok(0x72,0x700352f6);call(0x0a001275);br(0x3a,'layer',False)
mark('end');emit(0x16,0x2a)
for at,base,dest,short in fix:
 delta=labels[dest]-base
 if short:
  assert -128<=delta<=127,(at,dest,delta);b[at]=delta&255
 else:b[at:at+4]=struct.pack('<i',delta)

objects=Path(sys.argv[1]).read_bytes()
original=Path(sys.argv[2]).read_bytes()
assert len(objects)==681 and len(original)==243 and len(b)==len(original)
assert objects[0x298:]==bytes.fromhex('0472305203706f7512000a3a58fdffff2a')
# The original loop returns to offset zero, resetting per-object locals.
assert 0x2a8 + struct.unpack_from('<i',objects,0x2a4)[0] == 0
out="// Supported APK parser bodies; generated by scripts/gen_stage_parse.py.\n#pragma once\n#include <stdint.h>\n#define STAGE_PARSE_MVID \"4900a8e6-ea01-4e8a-ae66-036836545dd2\"\n#define STAGE_PARSE_BATCH 16\n#define STAGE_PARSE_LOOP_AT 0x298\n#define STAGE_PARSE_LOOP_SIZE 16\n"
for name,data in [('stage_objects_il',objects),('stage_layer_il',original),('stage_layer_batched_il',b)]:
 out+='static const uint8_t '+name+'[] = {\n'
 for at in range(0,len(data),24):out+='  '+','.join('0x%02x'%x for x in data[at:at+24])+',\n'
 out+='};\n'
Path(sys.argv[3]).write_text(out)
print('layer steps limited to 16 objects; IL size unchanged:',len(b))
